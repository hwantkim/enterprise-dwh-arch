# MAGIC
# MAGIC | 구동 요인 | 예시 | 영향 |
# MAGIC |--------|------|------|
# MAGIC | **데이터 거주 요건** | GDPR, CCPA, 데이터 주권 법률 | 컴플라이언스 규정을 준수하는 리전에 워크스페이스와 스토리지 필요 |
# MAGIC | **규제 분리** | 금융, 헬스케어, 정부 | 감사 요건이 별도 환경 요구 |
# MAGIC | **네트워크 분할** | 데이터 민감도에 따른 보안 영역 | 워크스페이스마다 네트워크 구성 상이 |
# MAGIC | **조직 경계** | 합병, 인수, 자회사 | 독립적 거버넌스 요건 |
# MAGIC | **환경 분리** | Dev, 스테이징, 프로덕션 | 개발 활동이 프로덕션 안정성과 SLA에 영향 방지 |
