# MAGIC 1. **다중 워크스페이스는 종종 요건** — 데이터 거주, 규제 분리, 조직 경계가 분리를 요구
# MAGIC 2. **비용 귀속이 설계 주도** — 워크스페이스는 빌링 경계, 태그는 프로젝트 수준 세분성
# MAGIC 3. **컴퓨팅 격리로 노이지 네이버 방지** — 별도 SQL 웨어하우스 풀로 각 팀 자체 리소스 보장
# MAGIC 4. **적은 수로 시작, 필요시 분할** — 과도한 분할은 관리 오버헤드 발생
# MAGIC 5. **극단 회피** — 하나의 워크스페이스도, 프로젝트당 하나도 최적이 아님. 구체적 구동 요인에 기반해 균형 필요