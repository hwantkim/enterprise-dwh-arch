# MAGIC
# MAGIC ### ❌ 안티패턴
# MAGIC
# MAGIC 1. **프로젝트별 워크스페이스:** 관리 오버헤드 발생, 거버넌스 분산 → 카탈로그와 스키마 사용
# MAGIC 2. **모두가 하나의 워크스페이스:** 격리 없음, 복잡한 권한, 큰 블라스트 반경
# MAGIC 3. **과도한 격리:** 소규모 팀에 별도 워크스페이스 → 구성/모니터링/라이프사이클 관리 오버헤드 수반
# MAGIC 4. **혼합 환경:** 단일 워크스페이스에 dev/test/prod 결합 → 우발적 데이터 손상 위험, 감사 어려움
