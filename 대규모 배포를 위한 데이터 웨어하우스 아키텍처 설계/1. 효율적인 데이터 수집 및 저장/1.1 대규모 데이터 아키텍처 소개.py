# DBTITLE 1,Lakehouse 아키텍처
# MAGIC %md
# MAGIC ## 4. Lakehouse 아키텍처 기초
# MAGIC
# MAGIC Lakehouse는 데이터 레이크(저렴, 유연, 불안정)와 데이터 웨어하우스(비쌈, 구조화, 안정적) 간의 갈등을 해결하는 **통합 플랫폼**입니다.
# MAGIC
# MAGIC **핵심 원칙:**
# MAGIC
# MAGIC * **데이터의 단일 복사본** - 레이크와 웨어하우스 간 사일로 제거, BI/ML/스트리밍을 위한 단일 진실 공급원
# MAGIC * **오픈 포맷** - Delta Lake, Parquet, Apache Iceberg로 벤더 종속성 방지
# MAGIC * **ACID 트랜잭션** - 동시 읽기/쓰기에도 안정성 보장
# MAGIC * **스키마 적용** - 잘못된 데이터 유입 방지
# MAGIC * **타임 트래블** - 과거 버전 쿼리 및 실수 복구

# COMMAND ----------

# DBTITLE 1,메달리온 아키텍처
# MAGIC %md
# MAGIC ## 5. 메달리온 아키텍처 (Bronze / Silver / Gold)
# MAGIC
# MAGIC Lakehouse에서 데이터를 구성하는 검증된 패턴: **외부 소스 → Bronze → Silver → Gold → BI/ML/애플리케이션**
# MAGIC
# MAGIC | 계층 | 목적 | 특징 |
# MAGIC |---|---|---|
# MAGIC | **Bronze (원본)** | 원본 형식의 수집된 데이터 + 메타데이터 | 추가 전용, 전체 이력, 최소 변환 |
# MAGIC | **Silver (정제됨)** | 검증, 중복 제거, 보강된 데이터 | 표준화된 스키마, 비즈니스 규칙 적용 |
# MAGIC | **Gold (큐레이션)** | 비즈니스 수준 집계 및 피처 스토어 | 사용 사례 최적화, 종종 비정규화 |
# MAGIC
# MAGIC > **주의:** 계층을 건너뛰지 마세요. Bronze는 감사 추적과 복구 옵션을 제공하며, 문제 발생 시 **재생 버퍼** 역할을 합니다. 소스에서 Gold로 직접 건너뛰면 오류 복구가 원본 소스에 의존하게 됩니다.

