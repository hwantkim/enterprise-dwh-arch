# DBTITLE 1,스케일의 의미
# MAGIC %md
# MAGIC ## 1. 스케일이란 무엇인가?
# MAGIC
# MAGIC 스케일은 단순히 데이터 볼륨만이 아니라 **5가지 차원**의 조합으로 이해해야 합니다:
# MAGIC
# MAGIC | 차원 | 소규모 | 엔터프라이즈 규모 |
# MAGIC |---|---|---|
# MAGIC | **동시 쿼리** | 5-10개 | 수백~수천 개 (핵심 지표: **쿼리 처리량**) |
# MAGIC | **데이터 볼륨** | 기가바이트 | 테라바이트~페타바이트 |
# MAGIC | **사용자 기반** | 소규모 팀 | 수천 명 (다수 부서/지역) |
# MAGIC | **지연 시간** | 분 단위 | 초~서브초 |
# MAGIC | **가용성** | 업무 시간 | 24/7 글로벌 |
# MAGIC
# MAGIC > **핵심 인사이트:** 각 차원은 서로의 영향을 **증폭**시킵니다. 소규모에서 10% 비효율은 무시할 수 있지만, 엔터프라이즈 규모에서는 수백만의 낭비된 비용으로 이어집니다.

# COMMAND ----------

# DBTITLE 1,수집 및 저장 결정의 증폭 효과
# MAGIC %md
# MAGIC ## 2. 스케일에서 수집 및 저장 결정이 더 중요한 이유
# MAGIC
# MAGIC 소규모에서는 컴퓨팅 자원 추가나 수동 재처리로 문제를 해결할 수 있지만, 엔터프라이즈 규모에서는 이러한 임시방편이 **치명적으로 실패**합니다:
# MAGIC
# MAGIC * **작은 비효율 → 주요 병목:** 수천 개의 쿼리에 곱해지면
# MAGIC * **부적절한 파일 레이아웃:** 1TB에서는 문제없지만 100TB에서는 심각한 병목
# MAGIC * **스키마 설계 결정:** 프로덕션 데이터는 거의 변경 불가능
# MAGIC * **비용 누적:** 10% 비효율 = 수백만의 낭비
# MAGIC * **성능 저하:** 개별 사용자가 아닌 전체 조직에 영향

# COMMAND ----------

# DBTITLE 1,주요 안티 패턴
# MAGIC %md
# MAGIC ## 3. 대규모 배포를 마비시키는 안티 패턴
# MAGIC
# MAGIC | 안티 패턴 | 스케일에서의 영향 |
# MAGIC |---|---|
# MAGIC | **작은 파일 문제** | 수백만 개의 작은 파일 → 메타데이터 오버헤드, 느린 쿼리 계획 |
# MAGIC | **통계 정보 누락** | 옵티마이저의 잘못된 결정 → 잘못된 조인, 불필요한 셔플, 전체 스캔 |
# MAGIC | **파티션 과잉** | 과도한 파티셔닝 → 디렉토리 폭발 (시간별 10년 = 87,600개) |
# MAGIC | **스키마 드리프트** | 소스 간 불일치 → ETL 실패, 잘못된 결과 |
# MAGIC | **클러스터링 부재** | 데이터 배치 불일치 → 과도한 I/O, 느린 성능 |
# MAGIC
# MAGIC > **안티 패턴 경고:** 이러한 문제는 기술 부채처럼 복합적으로 쌓입니다. **예방이 복구보다 저렴합니다.**

